// 5. Bold Slab Font (thick pixel weights)
const BOLD_FONT = cloneFont(DEFAULT_CP437_FONT);
for (let i = 33; i <= 126; i++) {
  const glyph = DEFAULT_CP437_FONT[i];
  if (glyph) {
    // Thicken by bitwise OR with shifted version
    BOLD_FONT[i] = glyph.map((row) => (row | (row >> 1)) & 0xff);
  }
}

