// Helper to deep clone glyphs
function cloneFont(font: Record<number, number[]>): Record<number, number[]> {
  const result: Record<number, number[]> = {};
  for (const [key, val] of Object.entries(font)) {
    result[parseInt(key, 10)] = [...val];
  }
  return result;
}

