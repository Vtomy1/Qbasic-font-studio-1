// Populate standard ASCII 33..126 metadata
for (let i = 33; i <= 126; i++) {
  const ch = String.fromCharCode(i);
  let name = `Character '${ch}'`;
  if (i >= 48 && i <= 57) name = `Digit ${ch}`;
  else if (i >= 65 && i <= 90) name = `Uppercase ${ch}`;
  else if (i >= 97 && i <= 122) name = `Lowercase ${ch}`;
  CP437_NAMES[i] = {
    symbol: ch,
    name,
    category: 'ascii',
  };
}

